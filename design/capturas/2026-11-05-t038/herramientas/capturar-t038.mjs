import { chromium } from 'playwright';
import { readFileSync, mkdirSync } from 'node:fs';
const cuentas = JSON.parse(readFileSync('/home/claude/nexoai-t038/apps/web/e2e/cuentas.json', 'utf8'));
const SALIDA = '/home/claude/capturas/salida/t038'; mkdirSync(SALIDA, { recursive: true });
const b = await chromium.launch(); const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, locale: 'es-PE', timezoneId: 'America/Lima' });
const page = await ctx.newPage();
await page.goto('http://localhost:3111/entrar', { timeout: 120000 });
await page.getByLabel('Correo').fill(cuentas.asistente.correo); await page.getByLabel('Contraseña').fill(cuentas.contrasenaTemporal);
await page.getByRole('button', { name: 'Entrar' }).click(); await page.getByRole('heading', { level: 1, name: 'Agenda' }).waitFor({ timeout: 120000 });
await page.waitForTimeout(800); await page.screenshot({ path: `${SALIDA}/T038-01-al-abrir.png` });
const pedir = async (t) => { await page.getByLabel('Pídele algo al asistente').fill(t); await page.getByRole('button', { name: 'Enviar' }).click(); };
await pedir('Agéndame una revisión mañana a las 9');
await page.getByRole('article', { name: 'Para confirmar' }).last().waitFor();
await page.getByRole('article', { name: 'Para confirmar' }).last().getByRole('button', { name: 'Confirmar' }).click();
await page.getByText(/^Listo: «Revisión»/).last().waitFor(); await page.waitForTimeout(500);
await page.screenshot({ path: `${SALIDA}/T038-02-confirmado.png` });
await pedir('Mejor a las 5'); await page.getByText('No sé hacer eso todavía.').last().waitFor(); await page.waitForTimeout(400);
await page.screenshot({ path: `${SALIDA}/T038-03-siguiente-mensaje.png` });
await page.reload(); await page.getByRole('heading', { level: 1, name: 'Agenda' }).waitFor(); await page.waitForTimeout(800);
await page.screenshot({ path: `${SALIDA}/T038-04-recarga.png` });
await b.close(); console.log('listo');
